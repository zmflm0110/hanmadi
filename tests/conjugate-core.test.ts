import { describe, expect, it } from 'vitest';
import { attachC, attachEu, attachFormal, honor, inferConj, infinitive, pastStem, type Pos } from '../src/engine/conjugate';

const v = (lemma: string, pos: Pos = 'verb') => ({ lemma, pos });
const a = (lemma: string) => v(lemma, 'adj');

describe('불규칙 추정', () => {
  it.each([
    [v('먹다'), 'regular'],
    [v('하다'), 'hada'],
    [v('공부하다'), 'hada'],
    [v('살다'), 'rieul'],
    [v('만들다'), 'rieul'],
    [v('쓰다'), 'eu'],
    [a('바쁘다'), 'eu'],
    [v('따르다'), 'eu'],
    [v('모르다'), 'reu'],
    [v('부르다'), 'reu'],
    [a('푸르다'), 'reo'],
    [v('푸다'), 'u'],
    [a('춥다'), 'b'],
    [a('어렵다'), 'b'],
    [v('돕다'), 'b-wa'],
    [a('곱다'), 'b-wa'],
    [v('눕다'), 'b'],
    [v('입다'), 'regular'],
    [v('잡다'), 'regular'],
    [a('좁다'), 'regular'],
    [v('듣다'), 'd'],
    [v('걷다'), 'd'],
    [v('받다'), 'regular'],
    [v('닫다'), 'regular'],
    [v('짓다'), 's'],
    [v('웃다'), 'regular'],
    [v('씻다'), 'regular'],
    [a('파랗다'), 'h'],
    [a('그렇다'), 'h'],
    [a('좋다'), 'regular'],
    [v('놓다'), 'regular'],
    [v('넣다'), 'regular'],
  ])('%o → %s', (p, c) => expect(inferConj(p)).toBe(c));
});

