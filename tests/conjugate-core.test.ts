describe('자음 어미 · 합쇼체', () => {
  it.each([
    [v('먹다'), '고', '먹고'],
    [v('살다'), '고', '살고'],
    [v('살다'), '는', '사는'],
    [v('만들다'), '네요', '만드네요'],
    [v('가다'), '지', '가지'],
  ])('%o + %s → %s', (p, rest, out) => expect(attachC(p, rest)).toBe(out));

  it.each([
    [v('가다'), '니다', '갑니다'],
    [v('먹다'), '니다', '먹습니다'],
    [v('살다'), '니다', '삽니다'],
    [v('만들다'), '니다', '만듭니다'],
    [v('하다'), '니다', '합니다'],
    [a('춥다'), '니다', '춥습니다'],
    [v('듣다'), '니까', '듣습니까'],
    [v('모르다'), '니다', '모릅니다'],
    [v('가다'), '시다', '갑시다'],
    [v('먹다'), '시다', '먹읍시다'],
    [v('놀다'), '시다', '놉시다'],
  ])('%o + ㅂ/습%s → %s', (p, rest, out) => expect(attachFormal(p, rest)).toBe(out));
});

describe('-(으)시-', () => {
  it.each([
    [v('가다'), '가시다'],
    [v('읽다'), '읽으시다'],
    [v('살다'), '사시다'],
    [v('돕다'), '도우시다'],
    [v('듣다'), '들으시다'],
  ])('%o → %s', (p, out) => expect(honor(p).lemma).toBe(out));

  it('이미 높임 낱말이면 그대로', () => {
    expect(honor({ lemma: '드시다', pos: 'verb', honorificLemma: true }).lemma).toBe('드시다');
  });
});
